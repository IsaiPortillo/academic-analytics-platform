-- METAS POR CARRERA, CON LA INSTITUCIONAL DE RESPALDO
-- =============================================================================
-- Hasta aquí había UNA meta por indicador: academico_oltp.metas_indicador tenía
-- clave primaria solo por `codigo`. Consecuencia: el coordinador de una carrera
-- veía el valor de SU carrera comparado contra la meta de toda la institución, y
-- la vista ejecutiva tenía que desactivar el semáforo del costo de reprobación
-- al filtrar, porque un subtotal nunca se compara con un total institucional.
--
-- Ahora la meta se guarda por (indicador, carrera), donde `carrera_id` nulo
-- significa LA META INSTITUCIONAL:
--
--   carrera_id IS NULL   meta general, la que ya existía
--   carrera_id = N       meta propia de esa carrera, que se antepone a la general
--
-- Así el decano define las generales como siempre y, además, las individuales
-- que quiera; ninguna carrera queda sin meta porque hereda la institucional
-- mientras nadie le ponga una propia. No hay que crear 12 × 5 = 60 filas para
-- que el sistema funcione.
--
-- Por qué NO se derivan solas desde las de carrera: de los cinco indicadores,
-- solo el costo de reprobación es aditivo (se podría sumar). Los otros cuatro
-- son razones o promedios por estudiante, y promediar las metas de las carreras
-- sería un promedio de promedios — el error que el proyecto evita en todas
-- partes. Derivar bien exigiría metas de numerador y denominador por separado.
--
-- NULLS NOT DISTINCT (PostgreSQL 15+) es lo que permite que «sin carrera» sea
-- una clave única real: sin eso, dos filas institucionales del mismo indicador
-- no chocarían, porque NULL <> NULL. Evita tener que inventar un centinela
-- (carrera_id = 0) y una fila falsa en `carreras`.
--
-- Idempotente.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. OLTP: la meta deja de ser única por indicador
-- -----------------------------------------------------------------------------
ALTER TABLE academico_oltp.metas_indicador
    ADD COLUMN IF NOT EXISTS carrera_id INT REFERENCES academico_oltp.carreras (carrera_id)
        ON DELETE CASCADE;

COMMENT ON COLUMN academico_oltp.metas_indicador.carrera_id IS
    'Carrera a la que aplica la meta. NULL = meta institucional, que es la que '
    'usan las carreras sin meta propia.';

-- Una clave primaria no admite columnas nulas, así que se cambia por una llave
-- sustituta más la restricción única que de verdad modela la regla.
ALTER TABLE academico_oltp.metas_indicador
    ADD COLUMN IF NOT EXISTS meta_id BIGINT GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE academico_oltp.metas_indicador DROP CONSTRAINT IF EXISTS metas_indicador_pkey;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = 'academico_oltp.metas_indicador'::regclass
                     AND conname = 'metas_indicador_pkey') THEN
        ALTER TABLE academico_oltp.metas_indicador ADD CONSTRAINT metas_indicador_pkey
            PRIMARY KEY (meta_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = 'academico_oltp.metas_indicador'::regclass
                     AND conname = 'uq_meta_indicador_carrera') THEN
        ALTER TABLE academico_oltp.metas_indicador ADD CONSTRAINT uq_meta_indicador_carrera
            UNIQUE NULLS NOT DISTINCT (codigo, carrera_id);
    END IF;
END $$;

-- -----------------------------------------------------------------------------
-- 2. Quién ve qué meta
-- -----------------------------------------------------------------------------
-- El coordinador ve la institucional (su respaldo) y la suya, nunca la de otra
-- carrera: una meta es información de gestión de esa carrera. Escribirlas sigue
-- siendo del admin (script 23 le quitó la escritura sobre esta tabla).
ALTER TABLE academico_oltp.metas_indicador ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS admin_todo ON academico_oltp.metas_indicador;
CREATE POLICY admin_todo ON academico_oltp.metas_indicador FOR ALL TO rol_admin
    USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS coordinador_su_carrera ON academico_oltp.metas_indicador;
CREATE POLICY coordinador_su_carrera ON academico_oltp.metas_indicador FOR SELECT TO rol_coordinador
    USING (carrera_id IS NULL OR carrera_id = academico_oltp.carrera_sesion());

DROP POLICY IF EXISTS etl_lectura ON academico_oltp.metas_indicador;
CREATE POLICY etl_lectura ON academico_oltp.metas_indicador FOR SELECT TO rol_etl
    USING (true);
